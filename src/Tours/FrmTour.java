    @Override
    public void delete() {
      if (tour == null) {
            UtilGui.showErrorMessage(this, "Debe especificar el animal a eliminar", "Error");
            return;
        }
        if (!list.remove(tour)) {
            JOptionPane.showMessageDialog(this, "No se elimino el registro");
        }
        clear();
    }

    @Override
    public void search() {
        DiaSearchTour frmSearch = new DiaSearchTour(this, true);
        frmSearch.setList(list);
        frmSearch.setVisible(true);
        tour = frmSearch.getTour();
        if (tour != null) {
            showData();
        }
    }

    @Override
    public void showData() {
        if (tour == null) {
            UtilGui.showErrorMessage(this, "Debe especificar el animal a eliminar", "Error");
            return;
        }
        txtId.setText(tour.getGuide().getId());
        txtTourDate.setText(UtilDate.toString(tour.getDate()));
        txtName.setText(tour.getGuide().getName());
    }
    
    private void addVisitorToTour() {

        String visitorId = txtVisitorId.getText();
        Visitor visitor = listVisitor.find(visitorId);

        if (visitor != null) {
            tourVisitors.add(visitor);
            model.addElement(visitor.getName());
            txtVisitorId.setText("");
        } else {
            UtilGui.showErrorMessage(this, "No se encontró un visitante con ese ID", "Error");
        }
}
