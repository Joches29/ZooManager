    @Override
    public void clear() {
         txtId.setText("");
         txtTourDate.setText("");
         txtName.setText("");
         txtVisitorId.setText("");
         model.clear();
    }

    @Override
    public boolean validateRequiere() {
        return UtilGui.validateRequiere(txtId);
    }

    @Override
    public void save() {
        if (!validateRequiere()) {
            UtilGui.showErrorMessage(this, "Faltan datos requeridos", "Error");
        }

        Guide guide = listGuide.find(txtId.getText());
        
        if (tourVisitors.isEmpty()) {
            UtilGui.showErrorMessage(this, "Debe agregar al menos un visitante", "Error");
            return;
        }
        
        tour = new Tour(guide,tourVisitors);

        if (!list.add(tour)) {
            JOptionPane.showMessageDialog(this, "No se agrego el registro");
            return;
        }
        UtilGui.showMessage(this, "Registro agregado " + tour.getGuide().getName(), " Agregado");
        tourVisitors.clear();
        model.clear();
    }

