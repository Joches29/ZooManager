    private void loadTable() {
        HashMap<String, Tour> map = list.getMap();
        model.setRowCount(0);
        for (Tour tour : map.values()) {
            Object[] data = {tour.getGuide().getId(), tour.getGuide().getName(), UtilDate.toString(tour.getDate())};
            model.addRow(data);
        }
    }
